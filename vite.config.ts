function hash(s: string): string {
  let h = 0
  for (let i = 0; i < s.length; i++) h = (Math.imul(31, h) + s.charCodeAt(i)) | 0
  return (h >>> 0).toString(36).slice(0, 6)
}

/** Inline CSS: .module.css -> hashed class map; all CSS is registered into __DIG_CSS__. */
function inlineCss(): any {
  const register = (css: string) =>
    `;(function(){try{var g=globalThis;g.__DIG_CSS__=g.__DIG_CSS__||[];` +
    `if(!g.__DIG_CSS_SEEN__)g.__DIG_CSS_SEEN__=new Set();` +
    `if(!g.__DIG_CSS_SEEN__.has(${JSON.stringify(css.length + ":" + css.slice(0, 40))})){` +
    `g.__DIG_CSS_SEEN__.add(${JSON.stringify(css.length + ":" + css.slice(0, 40))});g.__DIG_CSS__.push(${JSON.stringify(css)});}}catch(e){}})();\n`
  return {
    name: "dig-inline-css",
    enforce: "pre",
    load(id: string) {
      if (!id.endsWith(".css")) return null
      if (id.includes("node_modules")) return null
      const raw = fs.readFileSync(id, "utf8")
      if (!id.endsWith(".module.css"))
        return { code: register(raw) + "export default {};\n", moduleSideEffects: true }
      const suffix = hash(id)
      const globals: string[] = []
      let text = raw.replace(/:global\(([^)]*(?:\([^)]*\)[^)]*)*)\)/g, (_m, inner) => {
        globals.push(inner)
        return `__G${globals.length - 1}__`
      })
      const classes = new Map<string, string>()
      text = text.replace(/(^|[^a-zA-Z0-9_\-.\\])(\.)([_a-zA-Z][\w-]*)/g, (m, pre, dot, name) => {
        const scoped = `${name}__${suffix}`
        classes.set(name, scoped)
        return `${pre}${dot}${scoped}`
      })
      text = text.replace(/__G(\d+)__/g, (_m, i) => globals[Number(i)])
      return {
        code: register(text) + `export default ${JSON.stringify(Object.fromEntries(classes))};\n`,
        moduleSideEffects: true,
      }
    },
  }
}

const clientWrap: any = {
  name: "dig-client-wrapper",
  closeBundle() {
    const dir = path.resolve("dist")
    const bodyFile = path.join(dir, "client.body.js")
    if (!fs.existsSync(bodyFile)) return
    const body = fs.readFileSync(bodyFile, "utf8")
    let cssFile = path.join(dir, "style.css")
    if (!fs.existsSync(cssFile)) {
      const top = fs.existsSync(dir) ? fs.readdirSync(dir) : []
      const rootCss = top.find((f) => f.endsWith(".css"))
      if (rootCss) cssFile = path.join(dir, rootCss)
      else {
        const assets = fs.existsSync(path.join(dir, "assets"))
          ? fs.readdirSync(path.join(dir, "assets"))
          : []
        const found = assets.find((f) => f.endsWith(".css"))
        if (found) cssFile = path.join(dir, "assets", found)
      }
    }
    const css = fs.existsSync(cssFile) ? fs.readFileSync(cssFile, "utf8") : ""
    const cssReg = css
      ? `;(function(){try{var g=globalThis;g.__DIG_CSS__=g.__DIG_CSS__||[];g.__DIG_CSS__.push(${JSON.stringify(css)});}catch(e){}})();\n`
      : ""
    const wrapped =
      `// Generated by vp build (vite.config.ts) — edit src/client instead.\n` +
      `window.__ModuleLoader__.load({\n  id: ${JSON.stringify(PKG_ID)},\n  factory: (require) => {\n    var module = { exports: {} }, exports = module.exports;\n` +
      cssReg +
      body +
      `\n    return module.exports;\n  },\n});\n`
    fs.writeFileSync(path.join(dir, "client.js"), wrapped)
    fs.rmSync(bodyFile, { force: true })
    try {
      if (fs.existsSync(cssFile)) fs.rmSync(cssFile)
    } catch {}
  },
}

