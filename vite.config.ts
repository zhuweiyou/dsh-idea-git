import { defineConfig } from "vite-plus"
import fs from "node:fs"
import path from "node:path"

const PKG_ID = "dsh-idea-git"

const shared = {
  fmt: { semi: false, singleQuote: false, tabWidth: 2, useTabs: false, printWidth: 120 },
  test: { include: ["tests/**/*.test.ts"], testTimeout: 180000, hookTimeout: 180000 },
  lint: { options: { typeAware: true, typeCheck: true } },
}

const clientWrap: any = {
  name: "dig-client-wrapper",
  closeBundle() {
    const dir = path.resolve("dist")
    const bodyFile = path.join(dir, "client.body.js")
    if (!fs.existsSync(bodyFile)) return
    const body = fs.readFileSync(bodyFile, "utf8")
    let cssFile = path.join(dir, "style.css")
    if (!fs.existsSync(cssFile)) {
      const top = fs.existsSync(dir) ? fs.readdirSync(dir) : []
      const rootCss = top.find((f) => f.endsWith(".css"))
      if (rootCss) cssFile = path.join(dir, rootCss)
      else {
        const assets = fs.existsSync(path.join(dir, "assets")) ? fs.readdirSync(path.join(dir, "assets")) : []
        const found = assets.find((f) => f.endsWith(".css"))
        if (found) cssFile = path.join(dir, "assets", found)
      }
    }
    const css = fs.existsSync(cssFile) ? fs.readFileSync(cssFile, "utf8") : ""
    const cssReg = css
      ? `;(function(){try{var g=globalThis;g.__DIG_CSS__=g.__DIG_CSS__||[];g.__DIG_CSS__.push(${JSON.stringify(css)});}catch(e){}})();\n`
      : ""
    const wrapped =
      `// Generated by vp build (vite.config.ts) — edit src/client instead.\n` +
      `window.__ModuleLoader__.load({\n  id: ${JSON.stringify(PKG_ID)},\n  factory: (require) => {\n    var module = { exports: {} }, exports = module.exports;\n` +
      cssReg +
      body +
      `\n    return module.exports;\n  },\n});\n`
    fs.writeFileSync(path.join(dir, "client.js"), wrapped)
    fs.rmSync(bodyFile, { force: true })
    try {
      if (fs.existsSync(cssFile)) fs.rmSync(cssFile)
    } catch {}
  },
}

export default defineConfig(({ mode }) => {
  if (mode === "host") {
    return {
      ...shared,
      build: {
        ssr: "src/host/index.ts",
        outDir: "lib",
        emptyOutDir: false,
        target: "node20",
        sourcemap: false,
        rollupOptions: { output: { entryFileNames: "index.js" } },
      },
      logLevel: "info",
    }
  }
  return {
    ...shared,
    plugins: [clientWrap],
    resolve: {
      alias: {
        "react/jsx-runtime": path.resolve("src/client/jsx-runtime.ts"),
        "react/jsx-dev-runtime": path.resolve("src/client/jsx-runtime.ts"),
        "@": path.resolve("src/vendor"),
      },
    },
    build: {
      lib: { entry: "src/client/index.tsx", formats: ["cjs"], fileName: () => "client.body.js" },
      outDir: "dist",
      emptyOutDir: false,
      target: "es2020",
      minify: false,
      cssCodeSplit: false,
      rollupOptions: { external: ["react", "react-dom", "@deepseek-ai/dsh-client-ui-primitives"] },
    },
    logLevel: "info",
  }
})
