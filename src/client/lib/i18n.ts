export function setActiveLocale(id: string | null | undefined) {
  const next = /^zh/i.test(id ?? '') ? 'zh' : 'en'
  if (next !== active) {
    active = next
    subs.forEach((f) => { try { f() } catch {} })
  }
}

export function getActiveLocale(): string {
  return active
}

export function subscribeI18n(fn: () => void): () => void {
  subs.add(fn)
  return () => subs.delete(fn)
}

export function t(text: string, params?: Record<string, string | number>): string {
  let s = active === 'zh' ? (zh[text] ?? text) : text
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m))
  return s
}

export function useT(): (text: string, params?: Record<string, string | number>) => string {
  React.useSyncExternalStore(subscribeI18n, getActiveLocale)
  return t
}
