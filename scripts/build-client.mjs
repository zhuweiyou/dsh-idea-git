import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import fs from 'node:fs'
import path from 'node:path'

const root = path.dirname(fileURLToPath(import.meta.url))
const project = path.resolve(root, '..')
const PKG_ID = 'dsh-idea-git'

const outBody = path.join(project, 'dist/.client.body.js')
fs.mkdirSync(path.join(project, 'dist'), { recursive: true })

/**
 * Minimal CSS-modules loader for esbuild.
 * - `*.module.css` gets hashed class names and an exported class map.
 * - `*.css` is injected as-is.
 * Both register their CSS text into `globalThis.__DIG_CSS__` at module load; the
 * plugin's `apply` injects the collected sheet inside a `ctx.effect` so unmounting
 * removes it. No CSS file is emitted separately.
 */
function cssPlugin() {
  const hash = (s) => {
    let h = 0
    for (let i = 0; i < s.length; i++) h = (Math.imul(31, h) + s.charCodeAt(i)) | 0
    return (h >>> 0).toString(36).slice(0, 6)
  }
  const register = (css) =>
    `;(function(){try{var g=globalThis;g.__DIG_CSS__=g.__DIG_CSS__||[];` +
    `if(!g.__DIG_CSS_SEEN__)g.__DIG_CSS_SEEN__=new Set();` +
    `if(!g.__DIG_CSS_SEEN__.has(${JSON.stringify(css.length + ':' + css.slice(0, 40))})){` +
    `g.__DIG_CSS_SEEN__.add(${JSON.stringify(css.length + ':' + css.slice(0, 40))});g.__DIG_CSS__.push(${JSON.stringify(css)});}}catch(e){}})();\n`

  return {
    name: 'dig-css',
    setup(b) {
      b.onLoad({ filter: /\.css$/ }, async (args) => {
        const raw = fs.readFileSync(args.path, 'utf8')
        if (!/\.module\.css$/.test(args.path)) {
          return { contents: register(raw) + 'export default {};\n', loader: 'js' }
        }
        const suffix = hash(args.path)
        // Protect :global(...) segments from hashing.
        const globals = []
        let text = raw.replace(/:global\(([^)]*(?:\([^)]*\)[^)]*)*)\)/g, (_m, inner) => {
          globals.push(inner)
          return `__G${globals.length - 1}__`
        })
        const classes = new Map()
        text = text.replace(/(^|[^a-zA-Z0-9_\-.\\])(\.)([_a-zA-Z][\w-]*)/g, (m, pre, dot, name) => {
          const scoped = `${name}__${suffix}`
          classes.set(name, scoped)
          return `${pre}${dot}${scoped}`
        })
        text = text.replace(/__G(\d+)__/g, (_m, i) => globals[Number(i)])
        const map = Object.fromEntries(classes)
        return {
          contents: register(text) + `export default ${JSON.stringify(map)};\n`,
          loader: 'js',
        }
      })
    },
  }
}

await build({
  entryPoints: [path.join(project, 'src/client/index.tsx')],
  outfile: outBody,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  jsx: 'automatic',
  jsxImportSource: 'react',
  alias: {
    'react/jsx-runtime': path.join(project, 'src/client/jsx-runtime.ts'),
    'react/jsx-dev-runtime': path.join(project, 'src/client/jsx-runtime.ts'),
    '@': path.join(project, 'src/vendor'),
  },
  external: ['react', 'react-dom', '@deepseek-ai/dsh-client-ui-primitives'],
  plugins: [cssPlugin()],
  legalComments: 'none',
  logLevel: 'info',
})

const body = fs.readFileSync(outBody, 'utf8')
const wrapped =
  `// Generated by scripts/build-client.mjs — edit src/client instead.\n` +
  `window.__ModuleLoader__.load({\n  id: ${JSON.stringify(PKG_ID)},\n  factory: (require) => {\n    var module = { exports: {} }, exports = module.exports;\n` +
  body +
  `\n    return module.exports;\n  },\n});\n`
fs.writeFileSync(path.join(project, 'dist/client.js'), wrapped)
fs.rmSync(outBody, { force: true })
console.log(`[build-client] wrote dist/client.js (${wrapped.length} bytes)`)
