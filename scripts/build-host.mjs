import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.dirname(fileURLToPath(import.meta.url))
const project = path.resolve(root, '..')

await build({
  entryPoints: [path.join(project, 'src/host/index.ts')],
  outfile: path.join(project, 'lib/index.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  sourcemap: false,
  logLevel: 'info',
  // Keep the dynamically imported RPC module as part of the bundle.
  external: [],
  banner: { js: '// Generated by scripts/build-host.mjs — edit src/host instead.' },
})
